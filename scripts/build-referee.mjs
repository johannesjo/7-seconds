// Bundle the referee (src/server/edge-entry.ts) into one Deno-importable ESM
// module for the match-referee Edge Function. Bundled, not imported from
// source, because Deno can't resolve the app's extensionless imports; the
// output is committed so deploying needs no build step.
//
//   npm run referee:bundle   regenerate after changing the engine or the referee
//   npm run referee:check    fail if the committed bundle is out of date (CI)
//
// The bundle must stay DOM-free; this fails loudly if it ever reaches pixi or
// browser globals, instead of breaking the function at deploy time.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'supabase/functions/match-referee/referee.mjs';
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: ['src/server/edge-entry.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  banner: { js: '// @generated by scripts/build-referee.mjs from src/server/edge-entry.ts — do not edit by hand.' },
  legalComments: 'none',
});
const out = result.outputFiles[0].text;

const forbidden = [/from\s*["']pixi\.js["']/, /\bdocument\b/, /\bwindow\b/, /\bnavigator\b/, /HTMLCanvasElement/];
const hit = forbidden.find(re => re.test(out));
if (hit) {
  console.error(`referee bundle FAILED: it references a browser-only symbol (${hit}). The engine is no longer headless.`);
  process.exit(1);
}

if (check) {
  let committed = '';
  try { committed = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (committed !== out) {
    console.error(`${OUT} is out of date. Run npm run referee:bundle and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, out);
  console.log(`referee bundle OK → ${OUT} (${(out.length / 1024).toFixed(1)} kB, DOM-free)`);
}
