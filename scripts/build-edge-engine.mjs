// Bundle the headless engine (src/engine-entry.ts) into a single Deno-importable
// ESM module the Supabase `resolve-round` Edge Function imports. We bundle (not
// import source directly) because Deno can't resolve the app's extensionless
// relative imports, and we vendor the output so deploy needs no build step.
//
// Run: npm run build:edge   (re-run whenever the simulation changes)
//
// The bundle MUST stay DOM-free; this script asserts that the output references
// neither pixi nor the DOM, so a regression here fails loudly instead of
// breaking the function at deploy time.

import { build } from 'esbuild';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const OUT = 'supabase/functions/_shared/engine.mjs';
const BANNER = `// @generated by scripts/build-edge-engine.mjs from src/engine-entry.ts — do not edit by hand.\n`;

mkdirSync(dirname(OUT), { recursive: true });

await build({
  entryPoints: ['src/engine-entry.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: OUT,
  banner: { js: BANNER },
  legalComments: 'none',
});

const out = readFileSync(OUT, 'utf8');
const forbidden = [/from\s*["']pixi\.js["']/, /\bdocument\b/, /\bwindow\b/, /\bnavigator\b/, /HTMLCanvasElement/];
const hit = forbidden.find((re) => re.test(out));
if (hit) {
  console.error(`build:edge FAILED — bundle references a browser-only symbol (${hit}). The engine is no longer headless.`);
  process.exit(1);
}

// Re-write with the banner preserved (esbuild already added it) and report size.
writeFileSync(OUT, out);
console.log(`build:edge OK → ${OUT} (${(out.length / 1024).toFixed(1)} kB, DOM-free)`);
